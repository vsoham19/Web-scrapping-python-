#str
a = "Hello, World!"
print(a)
print(type(a))
#int
b = 20  
print(b)
print(type(b))
#float
c = 20.5    
print(c)
print(type(c))
#complex
d = 1j  
print(d)
print(type(d))
#list
e = ["apple", "banana", "cherry"]
print(e)
print(type(e))
#tuple
f = ("apple", "banana", "cherry")
print(f)
print(type(f))
#range
g = range(6)
print(g)
print(type(g))
#set
h = {"apple", "banana", "cherry"}
print(h)
print(type(h))
#frozenset
i = frozenset({"apple", "banana", "cherry"})
print(i)
print(type(i))
#dict
j = {"name": "John", "age": 36}
print(j)
print(type(j))
#bool
k = True
print(k)
print(type(k))
#bytes
l = b"Hello"
print(l)
print(type(l))
#bytearray
m = bytearray(5)
print(m)
print(type(m))
#memoryview
n = memoryview(bytes(5))
print(n)
print(type(n))
#NoneType
o = None
print(o)
print(type(o))
